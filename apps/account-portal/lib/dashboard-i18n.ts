export const dashboardMessages = {
	"zh-CN": chineseDashboardMessages,
	en: englishDashboardMessages,
} as const satisfies Record<Locale, Record<string, string>>;

export type DashboardMessages = (typeof dashboardMessages)[Locale];
export type DashboardMessageKey = keyof DashboardMessages;

export function formatDashboardMessage(
	message: string,
	values?: Readonly<Record<string, string>>,
) {
	if (!values) return message;
	return message.replace(/\{([^}]+)\}/g, (placeholder, key: string) =>
		Object.hasOwn(values, key) ? (values[key] ?? placeholder) : placeholder,
	);
}
